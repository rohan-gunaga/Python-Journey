a = 5
b = 3

# bitwise AND
print(a & b)

# bitwise OR
print(a | b)

# bitwise XOR
print(a ^ b)

# bitwise NOT
print(~a)

# Left shift
print(a << 1)

# Right shift
print(a >> 1)

